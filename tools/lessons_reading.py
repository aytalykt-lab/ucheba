def q(text, right, wrong1, wrong2, why=None, kind="concept"):
    item = {"q": text, "options": [str(right), str(wrong1), str(wrong2)], "correct": 0, "type": kind}
    if why:
        item["why"] = why
    return item


def lesson(id, title, goal, teach, walk, practice, questions, corrective, recheck):
    assert len(teach) == 4 and len(walk) == 3 and len(practice) == 2, id
    assert len(questions) == 6 and len(corrective) == 2 and len(recheck) == 6, id
    for item in practice + questions + recheck:
        assert len(set(item["options"])) == 3, item
    return {
        "id": id, "title": title, "video": "", "goal": goal,
        "text": teach[0], "example": walk[-1], "teach": teach, "walk": walk,
        "practice": practice, "questions": questions, "corrective": corrective, "recheck": recheck,
    }


