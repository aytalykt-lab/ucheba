def main():
    path = ROOT / "data.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    subject = next(s for s in data["subjects"] if s["id"] == "english")
    for new in LESSONS:
        at = next((i for i, l in enumerate(subject["lessons"]) if l["id"] == new["id"]), None)
        if at is None:
            subject["lessons"].append(new)
        else:
            subject["lessons"][at] = new
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("Уроков английского:", len(subject["lessons"]))


if __name__ == "__main__":
    main()
