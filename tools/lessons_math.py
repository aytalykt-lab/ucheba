def main():
    path = ROOT / "data.json"
    data = json.loads(path.read_text(encoding="utf-8"))
    math = next(s for s in data["subjects"] if s["id"] == "math")
    for new in LESSONS:
        at = next((i for i, l in enumerate(math["lessons"]) if l["id"] == new["id"]), None)
        if at is None:
            math["lessons"].append(new)
        else:
            math["lessons"][at] = new
    path.write_text(json.dumps(data, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
    print("Уроков математики:", len(math["lessons"]))


if __name__ == "__main__":
    main()
